from __future__ import absolute_import, print_function

import io
from datetime import datetime

__version__ = '0.1.0'


# - Read -------------------------------------------------------------------
def _number(text):
	value = float(text)
	return int(value) if value.is_integer() else value


def parse(text):
	'''Parse AFM text.

	Returns dict:
		font_name (str)  : FontName, or ''
		glyphs (list)    : glyph names from CharMetrics (N), in file order - the coverage
		kerning (dict)   : {(left, right): value} from KPX / KP (x part); a repeated pair keeps the last
		skipped (dict)   : counts of lines read but not used: KPY (vertical), KPH (hex names)
	'''
	out = {'font_name': '', 'glyphs': [], 'kerning': {}, 'skipped': {'KPY': 0, 'KPH': 0}}
	section = None
	for raw in text.splitlines():
		line = raw.strip()
		if not line or line.startswith('Comment'):
			continue
		word = line.split(None, 1)[0]

		if word == 'FontName':
			out['font_name'] = line[len(word):].strip()
		elif word == 'StartCharMetrics':
			section = 'chars'
		elif word == 'EndCharMetrics':
			section = None
		elif word.startswith('StartKernPairs'):
			section = 'kern'
		elif word == 'EndKernPairs':
			section = None
		elif section == 'chars':
			for field in line.split(';'):
				parts = field.split()
				if len(parts) >= 2 and parts[0] == 'N':
					out['glyphs'].append(parts[1])
					break
		elif section == 'kern':
			parts = line.split()
			if word == 'KPX' and len(parts) >= 4:
				out['kerning'][(parts[1], parts[2])] = _number(parts[3])
			elif word == 'KP' and len(parts) >= 5:
				out['kerning'][(parts[1], parts[2])] = _number(parts[3])
			elif word in out['skipped']:
				out['skipped'][word] += 1
	return out


def read(path, encoding='utf-8'):
	with io.open(path, 'r', encoding=encoding, errors='replace') as source:
		return parse(source.read())


# - Write ------------------------------------------------------------------
def dumps(pairs, glyphs=None, font_name='', comment='Generated by TypeRig (www.typerig.com)'):
	'''AFM text with KPX pairs ({(left, right): value} or [(left, right, value)]).
	glyphs, when given, are written as CharMetrics (no widths: WX 0).'''
	items = sorted(pairs.items()) if isinstance(pairs, dict) else [((l, r), v) for l, r, v in pairs]
	lines = ['StartFontMetrics 2.0',
	         'Comment %s' % comment,
	         'Comment Created on: %s' % datetime.now().strftime('%Y-%m-%d %H:%M:%S')]
	if font_name:
		lines.append('FontName %s' % font_name)
	if glyphs:
		lines.append('StartCharMetrics %d' % len(glyphs))
		lines.extend('C -1 ; WX 0 ; N %s ;' % name for name in glyphs)
		lines.append('EndCharMetrics')
	lines.append('StartKernData')
	lines.append('StartKernPairs %d' % len(items))
	lines.extend('KPX %s %s %s' % (left, right, value) for (left, right), value in items)
	lines += ['EndKernPairs', 'EndKernData', 'EndFontMetrics', '']
	return '\n'.join(lines)


def write(path, pairs, glyphs=None, font_name='', encoding='utf-8'):
	with io.open(path, 'w', encoding=encoding) as target:
		target.write(dumps(pairs, glyphs, font_name))
